public class VariaveisConplexas {

    public static void main(String[] args) {
        //Criando os primeiros vetores
        int []idade= {15,16,12,19,20};
        String [] nome={"Ana","Pedro","Luiza","Maria"," Kaio"};
        double [] salario ={1800, 1512.50,2500.83,1912.90,600};
    
        //Iprimir os dados da primeira pessoa
        
        System.out.println("nome:"+nome [0]);
        System.out.println("idade:"+idade[0]); 
        System.out.println("Salario:"+salario[0]);
        System.out.println("===========================");
        
        System.out.println("nome:"+nome [1]);
        System.out.println("idade:"+idade[1]);
        System.out.println("Salario:"+salario[1]);
        System.out.println("===========================");
        
        System.out.println("nome:"+nome [2]);
        System.out.println("idade:"+idade[2]);
        System.out.println("Salario:"+salario[2]);
        System.out.println("===========================");
        
        System.out.println("nome:"+nome [3]);
        System.out.println("idade:"+idade[3]);
        System.out.println("Salario:"+salario[3]);
        System.out.println("===========================");
        
        System.out.println("nome:"+nome [4]);
        System.out.println("idade:"+idade[4]);
        System.out.println("Salario:"+salario[4]);
    }
}
